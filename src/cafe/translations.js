/** `text` with each `{name}` replaced by `vars.name`. */
export function fillIn(text, vars) {
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (whole, name) => (vars[name] === undefined ? whole : String(vars[name])));
}

/**
 * A phrase in `language`: this table's translation, else Streamline's, else the
 * English it was asked by. `streamline(key)` is Streamline's own lookup, which
 * answers the key itself when it has no translation.
 */
export function cafeTranslation(key, language, streamline, vars) {
    const own = Object.prototype.hasOwnProperty.call(CAFE_TRANSLATIONS, key) ? CAFE_TRANSLATIONS[key][language] : undefined;
    return fillIn(typeof own === 'string' && own ? own : streamline(key), vars);
}

// Streamline's language codes that are not the tags a browser formats dates by.
const DATE_LOCALES = { 'de-ch': 'de-CH', 'zh-hans': 'zh-Hans', 'zh-hant': 'zh-Hant', kr: 'ko', arb: 'ar', heb: 'he', no: 'nb' };

/**
 * The locale to format a date in for one of Streamline's languages, so a month
 * is named in the language the page is in. A language Streamline has not
 * finished shows English text, and so an English date.
 */
export function dateLocale(language) {
    const code = String(language || 'en');
    if (code.includes('unfinished')) return 'en';
    return DATE_LOCALES[code] || code;
}
